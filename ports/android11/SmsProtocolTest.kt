import me.phh.sip.*

fun main() {
    check(normalizeSmsc("0791447758100650") == "+447785016005")
    check(normalizeSmsc("04912143F5") == "+12345")
    check(normalizeSmsc("04812143F5") == "12345")
    check(normalizeSmsc(" +447785016005 ") == "+447785016005")
    check(normalizeSmsc("447785016005") == "447785016005")
    check(normalizeSmsc("\"+447785016005\",145") == "+447785016005")
    check(normalizeSmsc("\"447785016005\", 145") == "+447785016005")
    check(normalizeSmsc("\"07785016005\",129") == "07785016005")
    check(normalizeSmsc("\"+447785016005\",999") == null)
    check(normalizeSmsc(null) == null)
    check(normalizeSmsc("") == null)
    check(normalizeSmsc("049121F345") == null)
    check(normalizeSmsc("04912A43F5") == null)
    check(normalizeSmsc("079144775810065000") == null)
    check(normalizeSmsc("07914477581006") == null)
    check(normalizeSmsc("04912143F500") == null)
    check(normalizeSmsc("+447785016005\r\nX: bad") == null)
    check(normalizeSmsPsi("sip:ipsmms1mc05.ims.mnc015.mcc234.3gppnetwork.org") != null)
    check(normalizeSmsPsi("<sip:+447785016005@example.org>") == "sip:+447785016005@example.org")
    check(normalizeSmsPsi("sip:sip:example.org") == null)
    check(normalizeSmsPsi("sip:example.org\r\nTo: bad") == null)
    check(decodeRpErrorCause(byteArrayOf(5, 42, 1, 38)) == 38)
    check(decodeRpErrorCause(byteArrayOf(5, 42, 2, 41, 0)) == 41)
    check(decodeRpErrorCause(byteArrayOf(5, 42, 2, 41)) == null)
    check(decodeRpErrorCause(byteArrayOf(5, 42, 0)) == null)
    check(decodeRpErrorCause(byteArrayOf(3, 42)) == null)
    val accepted = SmsSubmission()
    check(accepted.onSip(100) == null)
    check(accepted.onSip(200) == null) // SIP success alone is insufficient.
    check(accepted.onRp(true) == true)
    check(accepted.onRp(true) == null)
    check(accepted.expire() == null)
    val rejected = SmsSubmission()
    check(rejected.onSip(202) == null)
    check(rejected.onRp(false) == false)
    check(rejected.onRp(true) == null)
    val reversed = SmsSubmission()
    check(reversed.onRp(true) == null)
    check(reversed.onSip(200) == true)
    val timeout = SmsSubmission()
    check(timeout.onSip(200) == null)
    check(timeout.expire() == false)
    check(timeout.onRp(true) == null)
    val sipFailure = SmsSubmission()
    check(sipFailure.onSip(403) == false)
    check(sipFailure.expire() == null)
    println("41 SMS address, RP-cause and submission-order assertions passed")
}
